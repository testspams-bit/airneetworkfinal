const STORAGE_KEY_PREFIX = 'airneet_syllabus_progress_';

export function getSyllabusProgress(userId?: string): SyllabusProgressRecord {
  const key = `${STORAGE_KEY_PREFIX}${userId || 'guest'}`;
  try {
    const raw = localStorage.getItem(key);
    if (!raw) return {};
    return JSON.parse(raw);
  } catch (err) {
    console.error('Failed to load syllabus progress', err);
    return {};
  }
}

export function saveSyllabusProgress(record: SyllabusProgressRecord, userId?: string): void {
  const key = `${STORAGE_KEY_PREFIX}${userId || 'guest'}`;
  try {
    localStorage.setItem(key, JSON.stringify(record));
  } catch (err) {
    console.error('Failed to save syllabus progress', err);
  }
}

export function calculateChapterStatus(progress?: ChapterProgress): 'not_started' | 'in_progress' | 'mastered' {
  if (!progress) return 'not_started';
  const steps = [
    progress.theoryDone,
    progress.ncertDone,
    progress.notesDone,
    progress.pyqsDone,
    progress.rev1Done,
    progress.rev2Done,
  ];
  const completedCount = steps.filter(Boolean).length;
  if (completedCount === 0) return 'not_started';
  if (completedCount >= 5 && progress.confidence === 'mastered') return 'mastered';
  return 'in_progress';
}
